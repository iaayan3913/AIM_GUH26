// Local care-plan database (Hyperbee on Corestore). 100% local, no servers.
// Single writer: only the family worker's PC writes. Other peers get read-only replicas.
//
// Keys:
//   plan/<child_id>/latest          -> current plan (full JSON)
//   plan/<child_id>/v/<ISO time>    -> every saved version (history, never deleted)

//
// Encryption at rest (optional): set FOBE_DB_PASSPHRASE (or pass { encryptionKey }) and every
// Hypercore block is encrypted (XSalsa20, key = Argon2id(passphrase)). Unset = plain, as before.

import Corestore from 'corestore'
import Hyperbee from 'hyperbee'
import sodium from 'sodium-universal'

export async function openDb (storageDir = './data/office-pc', { key = null, encryptionKey = keyFromPassphrase(process.env.FOBE_DB_PASSPHRASE) } = {}) {
  const store = new Corestore(storageDir)
  await store.ready()
  // No key = we own the writable core. Key = read-only replica of someone else's db.
  const encryption = encryptionKey ? { key: encryptionKey } : null
  const core = key ? store.get({ key: Buffer.from(key, 'hex'), encryption }) : store.get({ name: 'care-plans', encryption })
  const bee = new Hyperbee(core, { keyEncoding: 'utf-8', valueEncoding: 'json' })
  await bee.ready()
  // Office DB: refuse a wrong/missing passphrase up front. (Replicas may hold ciphertext only.)
  if (core.writable && core.length > 0 && await core.has(0)) {
    const header = await bee.getHeader({ wait: false }).catch(() => null)
    if (header?.protocol !== 'hyperbee') {
      await store.close()
      throw new Error(`Cannot read care plans in ${storageDir}: ${encryptionKey ? 'wrong passphrase, or the data is not encrypted' : 'the data is encrypted, set FOBE_DB_PASSPHRASE'}`)
    }
  }

  return {
    store,
    bee,
    core,
    key: core.key.toString('hex'),
    writable: core.writable,

    async putPlan (plan) {
      if (!plan?.child_id) throw new Error('plan.child_id is required')
      const now = new Date().toISOString()
      const saved = { ...plan, saved_at: now }
      const batch = bee.batch()
      await batch.put(`plan/${plan.child_id}/latest`, saved)
      await batch.put(`plan/${plan.child_id}/v/${now}`, saved)
      await batch.flush()
      return saved
    },

    async getPlan (childId) {
      const node = await bee.get(`plan/${childId}/latest`)
      return node ? node.value : null
    },

    async listPlans () {
      const out = []
      for await (const { key, value } of bee.createReadStream({ gt: 'plan/', lt: 'plan0' })) {
        if (key.endsWith('/latest')) out.push(value)
      }
      return out
    },

    async history (childId) {
      const out = []
      const prefix = `plan/${childId}/v/`
      for await (const { value } of bee.createReadStream({ gt: prefix, lt: prefix + '~' })) out.push(value)
      return out // oldest first
    },

    async close () { await bee.close(); await store.close() }
  }
}

// Wrap compact seed values into the shared {value, source, status} field format.
export function wrapField (value, source = 'Approved care plan (seed data)') {
  const empty = value === undefined || value === null || value === '' || (Array.isArray(value) && value.length === 0)
  return { value: empty ? null : value, source: empty ? null : source, status: empty ? 'missing' : 'filled' }
}

export function compactToPlan (c) {
  const f = wrapField
  return {
    child_id: c.child_id,
    last_updated: f(c.last_updated),
    first_name: f(c.first_name),
    surname: f(c.surname),
    dob: f(c.dob),
    gender: f(c.gender),
    ethnicity: f(c.ethnicity),
    photo_consent: f(c.photo_consent),
    photo_path: null,
    diagnosis: f(c.diagnosis),
    medication: f(c.medication),
    allergies: f(c.allergies),
    emergency_contact: f(c.emergency_contact),
    about_me: {
      hobbies_interests: f(c.about_me?.hobbies_interests),
      watch_out: f(c.about_me?.watch_out)
    },
    attributes: {
      physical_mobility: f(c.attributes?.physical_mobility),
      communication_learning: f(c.attributes?.communication_learning),
      emotional_social: f(c.attributes?.emotional_social),
      toileting_self_care: f(c.attributes?.toileting_self_care),
      dietary: f(c.attributes?.dietary),
      words_phrases: f(c.attributes?.words_phrases)
    },
    challenging_behaviours: f(c.challenging_behaviours),
    approved_by: 'Family Worker (seed)',
    approved_at: c.last_updated + 'T12:00:00.000Z'
  }
}

// Age is computed, never generated by the AI.
export function ageFromDob (dob, today = new Date()) {
  const d = new Date(dob)
  let age = today.getFullYear() - d.getFullYear()
  const m = today.getMonth() - d.getMonth()
  if (m < 0 || (m === 0 && today.getDate() < d.getDate())) age--
  return age
}

// Annual review: due one year after last_updated.
export function reviewDue (lastUpdated) {
  const d = new Date(lastUpdated)
  d.setFullYear(d.getFullYear() + 1)
  return d.toISOString().slice(0, 10)
}

// 32-byte encryption key from a passphrase (Argon2id). Same passphrase = same key on every device.
export function keyFromPassphrase (passphrase) {
  if (!passphrase) return null
  const out = Buffer.alloc(32)
  const salt = Buffer.alloc(sodium.crypto_pwhash_SALTBYTES)
  sodium.crypto_generichash(salt, Buffer.from('fobe-care-plans-v1'))
  sodium.crypto_pwhash(out, Buffer.from(passphrase), salt, sodium.crypto_pwhash_OPSLIMIT_INTERACTIVE, sodium.crypto_pwhash_MEMLIMIT_INTERACTIVE, sodium.crypto_pwhash_ALG_ARGON2ID13)
  return out
}
